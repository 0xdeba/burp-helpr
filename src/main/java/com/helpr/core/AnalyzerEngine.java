package com.helpr.core;

import burp.api.montoya.MontoyaApi;
import burp.api.montoya.http.message.requests.HttpRequest;
import burp.api.montoya.proxy.http.*;
import com.helpr.api.SecurityTest;
import com.helpr.config.AnalyzerConfig;
import com.helpr.model.TestContext;
import com.helpr.model.TestResult;
import com.helpr.model.TrafficRecord;

import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.Queue;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.function.Consumer;

public final class AnalyzerEngine {
    private final MontoyaApi api;
    private final AnalyzerConfig config;
    private final TestRegistry registry;
    private final ExecutorService workers;
    private final Queue<TrafficRecord> traffic = new ConcurrentLinkedQueue<>();
    private final Queue<TestResult> results = new ConcurrentLinkedQueue<>();
    private final Map<Integer, TestContext> capturedContexts = new ConcurrentHashMap<>();
    private final Map<Integer, PendingRequest> pendingRequests = new ConcurrentHashMap<>();
    private final AtomicBoolean enabled = new AtomicBoolean(false);
    private final AtomicBoolean shutdown = new AtomicBoolean(false);
    private volatile Consumer<String> statusListener;

    public AnalyzerEngine(MontoyaApi api, AnalyzerConfig config, TestRegistry registry, Consumer<String> statusListener) {
        this.api = api;
        this.config = config;
        this.registry = registry;
        this.statusListener = statusListener;
        this.workers = Executors.newFixedThreadPool(4, r -> {
            Thread t = new Thread(r, "helpr-test-worker");
            t.setDaemon(true);
            return t;
        });
    }

    public void setStatusListener(Consumer<String> listener) {
        this.statusListener = listener == null ? ignored -> { } : listener;
    }

    public boolean isEnabled() { return enabled.get(); }

    public void setEnabled(boolean value) {
        if (shutdown.get()) return;
        enabled.set(value);
        statusListener.accept(value ? "Monitoring enabled — observing Burp Proxy traffic only" : "Monitoring disabled");
    }

    /**
     * Request-side gate: records only requests that entered Proxy while Helpr was enabled,
     * were in Burp Target Scope, and did not match an endpoint exclusion.
     * The request itself is never modified.
     */
    public ProxyRequestHandler requestHandler() {
        return new ProxyRequestHandler() {
            @Override
            public ProxyRequestReceivedAction handleRequestReceived(InterceptedRequest request) {
                try {
                    if (enabled.get() && request.isInScope()) {
                        String endpoint = request.url();
                        if (!config.isExcluded(endpoint) && !config.isIgnoredExtension(endpoint)) {
                            pendingRequests.put(request.messageId(), new PendingRequest(Instant.now()));
                            purgeStalePendingRequests();
                        }
                    }
                } catch (Exception e) {
                    api.logging().logToError("Helpr: Proxy request check failed: " + safeMessage(e));
                }
                return ProxyRequestReceivedAction.continueWith(request);
            }

            @Override
            public ProxyRequestToBeSentAction handleRequestToBeSent(InterceptedRequest request) {
                return ProxyRequestToBeSentAction.continueWith(request);
            }
        };
    }

    /**
     * Response-side handler completes an eligible Proxy exchange. A pending marker ensures
     * requests that entered Proxy while Helpr was ON are still processed if the toggle changes
     * before their response arrives. HTTP requests generated by api.http().sendRequest() do not
     * pass through this Proxy handler, preventing recursive testing.
     */
    public ProxyResponseHandler responseHandler() {
        return new ProxyResponseHandler() {
            @Override
            public ProxyResponseReceivedAction handleResponseReceived(InterceptedResponse response) {
                PendingRequest pending = pendingRequests.remove(response.messageId());
                if (pending != null) captureCompletedExchange(response);
                return ProxyResponseReceivedAction.continueWith(response);
            }

            @Override
            public ProxyResponseToBeSentAction handleResponseToBeSent(InterceptedResponse response) {
                return ProxyResponseToBeSentAction.continueWith(response);
            }
        };
    }

    private void captureCompletedExchange(InterceptedResponse response) {
        try {
            HttpRequest request = response.request();
            if (request == null || !request.isInScope()) return;

            String endpoint = request.url();
            if (config.isExcluded(endpoint) || config.isIgnoredExtension(endpoint)) return;

            String method = request.method();
            String rawRequest = request.toString();
            String rawResponse = response.toString();
            Instant capturedAt = Instant.now();

            traffic.add(new TrafficRecord(response.messageId(), endpoint, method,
                    rawRequest, rawResponse, capturedAt));
            statusListener.accept("Captured " + method + " " + endpoint);

            // This is the only place a test context is created. Therefore every test starts
            // from a completed request/response exchange observed by the Proxy handlers (the
            // same Proxy traffic represented in Proxy HTTP history); there is no URL crawler,
            // endpoint discovery, or independent request generation for test seeds.
            TestContext context = new TestContext(response.messageId(), endpoint, method,
                    rawRequest, rawResponse, request);
            capturedContexts.put(response.messageId(), context);

            // Modules replay clones of this captured request through Montoya's HTTP API.
            // Those replays bypass the Proxy listener and cannot recursively seed more tests.
            // No collection-time or execution-time deduplication: each eligible Proxy exchange
            // is passed independently to every enabled test case.
            for (SecurityTest test : registry.all()) {
                if (!test.isEnabled()) continue;
                workers.submit(() -> {
                    try {
                        test.execute(context, result -> {
                            results.add(result);
                            statusListener.accept("Tested " + result.testName() + " — " + result.status());
                        });
                    } catch (Exception e) {
                        api.logging().logToError("Helpr: " + test.id() + " failed: " + safeMessage(e));
                    }
                });
            }
        } catch (Exception e) {
            api.logging().logToError("Helpr: response capture failed: " + safeMessage(e));
        }
    }

    private void purgeStalePendingRequests() {
        if (pendingRequests.size() < 1000) return;
        Instant cutoff = Instant.now().minus(Duration.ofMinutes(10));
        pendingRequests.entrySet().removeIf(entry -> entry.getValue().createdAt().isBefore(cutoff));
    }

    public List<TrafficRecord> traffic() { return List.copyOf(traffic); }

    public List<TestResult> results() { return List.copyOf(results); }

    public void clearEvidence() {
        traffic.clear();
        results.clear();
        capturedContexts.clear();
        statusListener.accept("Evidence cleared");
    }

    public void shutdown() {
        if (!shutdown.compareAndSet(false, true)) return;
        enabled.set(false);
        pendingRequests.clear();
        workers.shutdownNow();
    }

    private static String safeMessage(Exception e) {
        return e.getMessage() == null ? e.getClass().getSimpleName() : e.getMessage();
    }

    private record PendingRequest(Instant createdAt) { }
}
